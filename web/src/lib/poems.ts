function gcd(a: number, b: number): number {
  return b === 0 ? a : gcd(b, a % b)
}

/**
 * Step through the list with a stride coprime to its length, so consecutive
 * half hours land on unrelated poems yet every poem appears once per cycle.
 */
const STRIDE = (() => {
  let s = 37
  while (gcd(s, POEMS.length) !== 1) s += 1
  return s
})()

/** Index of the half-hour slot containing `now`; the same for every visitor. */
export function poemSlot(now: number = Date.now()): number {
  return Math.floor(now / POEM_SLOT_MS)
}

export function poemForSlot(slot: number): Poem {
  const n = POEMS.length
  return POEMS[(((slot * STRIDE) % n) + n) % n]
}

/** Milliseconds until the next half-hour boundary. */
export function msUntilNextSlot(now: number = Date.now()): number {
  return POEM_SLOT_MS - (now % POEM_SLOT_MS)
}
